"""Export an approved question set as CSV or PDF (FR-4.7.1)."""
import csv
import io
from datetime import datetime
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from ..models import Q_DISCARDED, Submission


def _active(sub: Submission):
    return [q for q in sub.questions if q.state != Q_DISCARDED]


def to_csv(sub: Submission) -> bytes:
    a = sub.assignment
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["course", "assignment", "student_ref", "no", "question", "related_line", "node_type",
                "difficulty", "state", "marks"])
    for i, q in enumerate(_active(sub), 1):
        w.writerow([a.course.code, a.title, sub.student_ref, i, q.question_text, q.related_line,
                    q.related_node_type, q.difficulty, q.state, ""])
    return buf.getvalue().encode("utf-8-sig")  # BOM so Excel opens it correctly


def to_pdf(sub: Submission, approver_email: str | None) -> bytes:
    a = sub.assignment
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
                            topMargin=18 * mm, bottomMargin=18 * mm,
                            title=f"Viva - {sub.student_ref}", author="Adaptive Viva Generator")
    st = getSampleStyleSheet()
    body = ParagraphStyle("body", parent=st["BodyText"], fontSize=11, leading=15)
    small = ParagraphStyle("small", parent=body, fontSize=9, textColor=colors.HexColor("#555555"))

    approved = sub.approved_at.strftime("%d %b %Y") if isinstance(sub.approved_at, datetime) else "-"
    story = [
        Paragraph("Viva Question Sheet", st["Title"]),
        Table(
            [["Course", f"{a.course.code} - {a.course.title} ({a.course.term})"],
             ["Assignment", a.title],
             ["Student", sub.student_ref],
             ["Approved", f"{approved} by {approver_email or '-'}"]],
            colWidths=[30 * mm, None],
            style=TableStyle([("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
                              ("FONTSIZE", (0, 0), (-1, -1), 10),
                              ("BOTTOMPADDING", (0, 0), (-1, -1), 4)]),
        ),
        Spacer(1, 8 * mm),
    ]
    rows = [["#", "Question", "Line", "Level", "Marks"]]
    for i, q in enumerate(_active(sub), 1):
        rows.append([str(i), Paragraph(escape(q.question_text), body), str(q.related_line), q.difficulty, ""])
    t = Table(rows, colWidths=[8 * mm, None, 14 * mm, 18 * mm, 18 * mm], repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1e3a8a")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#999999")),
        ("TOPPADDING", (0, 1), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 1), (-1, -1), 10),
    ]))
    story += [t, Spacer(1, 10 * mm),
              Paragraph("Examiner remarks: ________________________________________________", body),
              Spacer(1, 6 * mm),
              Paragraph("Generated by Adaptive Viva Generator from AST analysis of the submitted code. "
                        "Line numbers refer to the submitted file.", small)]
    doc.build(story)
    return buf.getvalue()
